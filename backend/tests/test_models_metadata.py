"""Kiểm tra models khớp DDL đã chốt — KHÔNG cần database, chỉ cần SQLAlchemy.

Chạy:  cd backend && python -m pytest tests/test_models_metadata.py
"""
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.models import Base

TABLES = {"students", "courses", "course_offerings", "prerequisites", "completed_courses", "enrollments", "waitlist"}


def _ddl(table: str) -> str:
    return str(CreateTable(Base.metadata.tables[table]).compile(dialect=postgresql.dialect()))


def test_exactly_seven_tables():
    assert set(Base.metadata.tables) == TABLES


def test_primary_keys_are_identity_by_default():
    for t in ("students", "courses", "course_offerings", "enrollments", "waitlist"):
        assert "GENERATED BY DEFAULT AS IDENTITY" in _ddl(t), t


def test_check_constraints_are_named():
    expected = {
        "students": ["ck_students_role", "ck_students_max_credits", "ck_students_student_has_mssv"],
        "courses": ["ck_courses_credits"],
        "course_offerings": ["ck_offerings_capacity", "ck_offerings_enrolled_range"],
        "prerequisites": ["ck_prereq_type", "ck_prereq_no_self", "ck_prereq_group"],
        "completed_courses": ["ck_completed_grade"],
        "enrollments": ["ck_enrollments_status"],
        "waitlist": ["ck_waitlist_position"],
    }
    for table, names in expected.items():
        ddl = _ddl(table)
        for n in names:
            assert f"CONSTRAINT {n} CHECK" in ddl, (table, n)


def test_schedule_is_jsonb():
    assert "schedule JSONB NOT NULL" in _ddl("course_offerings")


def test_active_enrollment_is_partial_unique_index():
    idx = {i.name: i for i in Base.metadata.tables["enrollments"].indexes}
    sql = str(CreateIndex(idx["uq_enrollments_active"]).compile(dialect=postgresql.dialect()))
    assert "CREATE UNIQUE INDEX uq_enrollments_active" in sql
    assert "WHERE status = 'ACTIVE'" in sql
    assert set(idx) == {"uq_enrollments_active", "ix_enrollments_student", "ix_enrollments_offering"}


def test_cascade_rules():
    assert "ON DELETE CASCADE" in _ddl("waitlist")
    prereq = _ddl("prerequisites")
    # chỉ course_id có CASCADE; prereq_course_id thì KHÔNG (xóa môn đang là tiên quyết phải bị chặn)
    assert prereq.count("ON DELETE CASCADE") == 1
    assert "ON DELETE CASCADE" not in _ddl("course_offerings")


def test_prerequisite_composite_primary_key():
    cols = [c.name for c in Base.metadata.tables["prerequisites"].primary_key.columns]
    assert cols == ["course_id", "prereq_course_id"]
